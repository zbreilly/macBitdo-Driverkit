inline void encode(State s,uint8_t out[17]) {
    static const uint16_t bits[]={0x1000,0x2000,0x4000,0x8000,0x0100,0x0200,0x0020,0x0010,0x0040,0x0080,0x0400};
    static const uint8_t positions[]={0,1,3,4,6,7,10,11,13,14,12};
    uint16_t buttons=0;
    for(unsigned i=0;i<sizeof(bits)/sizeof(bits[0]);i++)if(s.buttons&bits[i])buttons|=1u<<positions[i];
    memset(out,0,17);out[0]=1;
    put16(out+1,axisUnsigned(s.lx,false));put16(out+3,axisUnsigned(s.ly,true));
    put16(out+5,axisUnsigned(s.rx,false));put16(out+7,axisUnsigned(s.ry,true));
    put16(out+9,((unsigned)s.lt*1023+127)/255);put16(out+11,((unsigned)s.rt*1023+127)/255);
    uint8_t h=hat(s.buttons);out[13]=h==8?0:h+1;
    put16(out+14,buttons);out[16]=!!(s.buttons&0x20);
}
typedef struct {
    uint8_t low, high;
    double on, delay;
    unsigned cycles;
} RumbleEffect;

inline int decodeRumble(uint32_t reportID, const uint8_t *p, size_t n, RumbleEffect *effect) {
    if (reportID != 3 || !p || !effect) return 0;
    if (n == 9) { if (*p++ != 3) return 0; n--; }
    if (n != 8 || (p[0] & 0xf0)) return 0;
    // Mask: bit 1 = low-frequency body motor; bit 0 = high-frequency.
    // Trigger motors are absent on this receiver and are not synthesized.
    *effect = RumbleEffect{
        static_cast<uint8_t>((p[0] & 2) ? ((p[3] > 100 ? 100 : p[3]) * 255u / 100u) : 0),
        static_cast<uint8_t>((p[0] & 1) ? ((p[4] > 100 ? 100 : p[4]) * 255u / 100u) : 0),
        p[5] * .01, p[6] * .01, (unsigned)p[7] + 1
    };
    return 1;
}

inline void encodeRumble(uint8_t low, uint8_t high, uint8_t out[8]) {
    const uint8_t packet[] = {0, 8, 0, low, high, 0, 0, 0};
    memcpy(out, packet, sizeof(packet));
}

inline void rumbleAt(RumbleEffect effect, double elapsed, uint8_t *low, uint8_t *high) {
    *low = *high = 0;
    double period = effect.delay + effect.on;
    if (elapsed < 0 || effect.on <= 0 || period <= 0 || elapsed >= period * effect.cycles) return;
    if (fmod(elapsed, period) < effect.delay) return;
    *low = effect.low; *high = effect.high;
}


